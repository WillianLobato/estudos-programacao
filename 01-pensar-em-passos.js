
/*
Pensar em passos (algoritmo) (Lógica)
Antes de codar, escreva em português o passo a passo. Fluxograma ou pseudocódigo ajudam muito aqui.

O que é
Algoritmo é uma sequência de passos, em ordem, para resolver um problema. Funciona como uma receita de bolo.

Como funciona
Antes de escrever código, você precisa saber resolver o problema com as suas palavras. O computador só faz o que você manda, passo a passo, sem adivinhar nada. Por isso cada passo precisa ser claro e estar na ordem certa.

Exemplos
Em português (pseudocódigo)
1. Pegue dois números
2. Some os dois
3. Mostre o resultado

JavaScript
let resultado = 2 + 3;
console.log(resultado);

Python
resultado = 2 + 3
print(resultado)
*/

