# Troque o valor de duas variáveis (a e b) sem perder nenhum.

valueA = 10
valueB = 20

print(f"Antes da troca: A = {valueA} e B = {valueB}")
print("\n")
# Troca de valores usando uma variável temporária
temp = valueA 
valueA = valueB
valueB = temp
print(f"Após a troca: A = {valueA} e B = {valueB}")
print("\n")
